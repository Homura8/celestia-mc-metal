package dev.celestia.metal.shader.pack;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.reflect.TypeToken;
import java.io.IOException;
import java.lang.reflect.Type;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Mutable per-pack option values, preset application, deterministic MSL {@code #define} generation,
 * and persistence (JSON for Native MSL packs; Iris {@code .txt} for Iris/OptiFine packs).
 */
public final class ShaderOptionState {
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().create();
    private static final Type MAP_TYPE = new TypeToken<Map<String, String>>() {}.getType();

    private final ShaderPackManifest manifest;
    private final Map<String, String> values = new LinkedHashMap<>();
    private String activePreset = "";

    public ShaderOptionState(ShaderPackManifest manifest) {
        this.manifest = manifest;
        resetToDefaults();
    }

    public ShaderPackManifest manifest() {
        return manifest;
    }

    public void resetToDefaults() {
        values.clear();
        for (ShaderOptionDef def : manifest.options) {
            values.put(def.id(), def.defaultValue());
        }
        if (manifest.presets.containsKey("Balanced")) {
            applyPreset("Balanced");
        } else if (!manifest.presets.isEmpty()) {
            applyPreset(manifest.presets.keySet().iterator().next());
        } else {
            activePreset = "";
        }
    }

    public void applyPreset(String presetName) {
        Map<String, String> overrides = manifest.presets.get(presetName);
        if (overrides == null) return;
        for (ShaderOptionDef def : manifest.options) {
            values.put(def.id(), def.defaultValue());
        }
        for (var e : overrides.entrySet()) {
            if (values.containsKey(e.getKey()) || findDef(e.getKey()) != null) {
                values.put(e.getKey(), e.getValue());
            }
        }
        activePreset = presetName;
    }

    public String activePreset() {
        return activePreset;
    }

    public String get(String optionId) {
        String v = values.get(optionId);
        if (v != null) return v;
        ShaderOptionDef def = findDef(optionId);
        return def != null ? def.defaultValue() : "";
    }

    public boolean getBoolean(String optionId) {
        String v = get(optionId);
        return "true".equalsIgnoreCase(v) || "1".equals(v);
    }

    public int getInt(String optionId) {
        try {
            return (int) Math.round(Double.parseDouble(get(optionId)));
        } catch (NumberFormatException e) {
            return 0;
        }
    }

    public double getDouble(String optionId) {
        try {
            return Double.parseDouble(get(optionId));
        } catch (NumberFormatException e) {
            return 0.0;
        }
    }

    public void set(String optionId, String value) {
        values.put(optionId, value);
        activePreset = detectMatchingPreset();
    }

    private String detectMatchingPreset() {
        for (var entry : manifest.presets.entrySet()) {
            boolean matches = true;
            for (ShaderOptionDef def : manifest.options) {
                String expected = entry.getValue().getOrDefault(def.id(), def.defaultValue());
                if (!expected.equals(get(def.id()))) {
                    matches = false;
                    break;
                }
            }
            if (matches) return entry.getKey();
        }
        return "Custom";
    }

    private ShaderOptionDef findDef(String id) {
        for (ShaderOptionDef d : manifest.options) {
            if (d.id().equals(id)) return d;
        }
        return null;
    }

    /**
     * Generates deterministic MSL preprocessor {@code #define} directives for all options.
     */
    public String toMslDefines() {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by Celestia Metal ShaderOptionState\n");
        for (ShaderOptionDef def : manifest.options) {
            String v = get(def.id());
            switch (def.kind()) {
                case TOGGLE -> sb.append("#define ").append(def.id()).append(' ')
                    .append(("true".equalsIgnoreCase(v) || "1".equals(v)) ? "1" : "0").append('\n');
                case ENUM -> {
                    int idx = Math.max(0, def.values().indexOf(v));
                    sb.append("#define ").append(def.id()).append(' ').append(idx).append('\n');
                    for (int i = 0; i < def.values().size(); i++) {
                        String sym = sanitizeIdent(def.id() + "_" + def.values().get(i).toUpperCase());
                        sb.append("#define ").append(sym).append(' ').append(i).append('\n');
                    }
                }
                case INT_SLIDER -> sb.append("#define ").append(def.id()).append(' ')
                    .append(getInt(def.id())).append('\n');
                case FLOAT_SLIDER -> sb.append("#define ").append(def.id()).append(' ')
                    .append(String.format(java.util.Locale.ROOT, "%.4ff", getDouble(def.id()))).append('\n');
            }
        }
        return sb.toString();
    }

    /**
     * Generates GLSL preprocessor {@code #define} directives for Iris/OptiFine shader packs.
     */
    public String toGlslDefines() {
        StringBuilder sb = new StringBuilder();
        for (ShaderOptionDef def : manifest.options) {
            String v = get(def.id());
            if (def.kind() == ShaderOptionDef.Kind.TOGGLE) {
                if ("true".equalsIgnoreCase(v) || "1".equals(v)) {
                    sb.append("#define ").append(def.id()).append('\n');
                }
            } else {
                sb.append("#define ").append(def.id()).append(' ').append(v).append('\n');
            }
        }
        return sb.toString();
    }

    public String configHash() {
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            md.update(manifest.id.getBytes(StandardCharsets.UTF_8));
            for (ShaderOptionDef def : manifest.options) {
                md.update(def.id().getBytes(StandardCharsets.UTF_8));
                md.update((byte) '=');
                md.update(get(def.id()).getBytes(StandardCharsets.UTF_8));
                md.update((byte) '\n');
            }
            return HexFormat.of().formatHex(md.digest()).substring(0, 16);
        } catch (Exception e) {
            return Integer.toHexString(values.hashCode());
        }
    }

    public Path configPath(Path shaderpacksDir) {
        String safeName = manifest.id.replace(':', '_').replace('/', '_');
        if (manifest.kind == ShaderPackManifest.PackKind.IRIS_GLSL && manifest.sourcePath != null) {
            return shaderpacksDir.resolve(manifest.sourcePath.getFileName().toString() + ".txt");
        }
        return shaderpacksDir.resolve(safeName + ".celestia.json");
    }

    public void loadFromDisk(Path shaderpacksDir) {
        Path p = configPath(shaderpacksDir);
        if (!Files.exists(p)) return;
        try {
            if (p.getFileName().toString().endsWith(".txt")) {
                for (String line : Files.readAllLines(p, StandardCharsets.UTF_8)) {
                    String trimmed = line.trim();
                    if (trimmed.isEmpty() || trimmed.startsWith("#")) continue;
                    int eq = trimmed.indexOf('=');
                    if (eq > 0) {
                        String k = trimmed.substring(0, eq).trim();
                        String v = trimmed.substring(eq + 1).trim();
                        values.put(k, v);
                    }
                }
            } else {
                Map<String, String> map = GSON.fromJson(Files.readString(p, StandardCharsets.UTF_8), MAP_TYPE);
                if (map != null) {
                    for (var e : map.entrySet()) {
                        if (values.containsKey(e.getKey())) values.put(e.getKey(), e.getValue());
                    }
                }
            }
            activePreset = detectMatchingPreset();
        } catch (IOException ignored) {
        }
    }

    public void saveToDisk(Path shaderpacksDir) {
        Path p = configPath(shaderpacksDir);
        try {
            Files.createDirectories(shaderpacksDir);
            if (p.getFileName().toString().endsWith(".txt")) {
                StringBuilder sb = new StringBuilder("# Celestia Metal Iris-compatible pack settings\n");
                for (var e : values.entrySet()) {
                    sb.append(e.getKey()).append('=').append(e.getValue()).append('\n');
                }
                Files.writeString(p, sb.toString(), StandardCharsets.UTF_8);
            } else {
                Files.writeString(p, GSON.toJson(values), StandardCharsets.UTF_8);
            }
        } catch (IOException ignored) {
        }
    }

    private static String sanitizeIdent(String s) {
        return s.replaceAll("[^A-Za-z0-9_]", "_");
    }
}
